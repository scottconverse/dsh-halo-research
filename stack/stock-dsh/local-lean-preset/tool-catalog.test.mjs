import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {homedir} from 'node:os';
import path from 'node:path';
import {apply} from './tool-catalog.mjs';
const require=createRequire(path.join(process.env.DSH_HOME || path.join(homedir(), '.dsh-stock'), 'profiles/package.json'));
const load=async n=>import(pathToFileURL(require.resolve(n)).href);
const {Context}=await load('@deepseek-ai/cordis');
const {SystemPrompt}=await load('@deepseek-ai/dsh-system-prompt');
const {ToolRuntime}=await load('@deepseek-ai/dsh-tools');
const {createScope,bindScopeParent}=await load('@deepseek-ai/dsh-scope');
const ctx=new Context();ctx.plugin(SystemPrompt,{});ctx.plugin(ToolRuntime,{});
await new Promise(r=>setImmediate(r));
const def=name=>({name,description:name,parameters:{type:'object',properties:{}},output:{schema:{type:'object'},render:()=>[]},execute:async()=>({})});
ctx.tools.register(def('mcp__research__search'));
ctx.systemPrompt.section({name:'mcp:research',order:20,text:'Research instruction'});
const fullKey={}, leanKey={}, childKey={};
const full=createScope(ctx,fullKey), lean=createScope(ctx,leanKey);
for(const [s,isLean] of [[full,false],[lean,true]])s.ctx.plugin({inject:['tools','systemPrompt'],apply(c){c.tools.register(def('pwsh'));if(isLean)apply(c);}});
const binding=bindScopeParent(childKey,leanKey);const child=createScope(ctx,childKey);
child.ctx.plugin({inject:['tools'],apply(c){c.tools.register(def('mcp__chrome__click'));c.tools.register(def('read_mcp_resource'));}});
await new Promise(r=>setImmediate(r));
const names=async scope=>(await ctx.systemPrompt.assemble({scope})).tools.map(t=>t.name).sort();
assert.deepEqual(await names(childKey),['pwsh']);
assert.deepEqual(await names(fullKey),['mcp__research__search','pwsh']);
assert.deepEqual(await names(),['mcp__research__search']);
const late=ctx.tools.register(def('mcp__late__fetch'));
assert.deepEqual(await names(childKey),['pwsh']);
assert.deepEqual(await names(fullKey),['mcp__late__fetch','mcp__research__search','pwsh']);
assert.ok(!(await ctx.systemPrompt.assemble({scope:childKey})).sections.some(s=>s.name==='mcp:research'));
assert.ok((await ctx.systemPrompt.assemble({scope:fullKey})).sections.some(s=>s.name==='mcp:research'));
binding.rebind(fullKey);
assert.deepEqual(await names(childKey),['mcp__chrome__click','mcp__late__fetch','mcp__research__search','pwsh','read_mcp_resource']);
late();await child.dispose();await lean.dispose();await full.dispose();
console.log('PASS: stock prompt assembly filters only lean, including agent-owned Chrome, late MCP registration and instructions; switching back restores full catalog.');

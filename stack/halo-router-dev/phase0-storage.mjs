import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
import {openLedger} from '../halo-routing/ledger.mjs';
const req=createRequire(import.meta.url);const host=createRequire(req.resolve('@deepseek-ai/dsh/package.json'));
const {JsonStorageBackend}=await import(pathToFileURL(host.resolve('@deepseek-ai/dsh-storage-json')));

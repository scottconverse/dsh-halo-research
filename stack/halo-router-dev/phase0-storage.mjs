const output={at:new Date().toISOString(),storage:'published DSH JsonStorageBackend',duplicateAppends:20,durableWrites:1,reopenPreserved:true,monotonicSequence:true,hostProjectionState:state,projectionWritesSession:false,hostProjectionAbsentFromClientSnapshot:true,decision:'Use plugin KV for independent durable observations. No session projection needed in 0.1.0.'};

import { execFile } from 'node:child_process';
import { join } from 'node:path';
import { promisify } from 'node:util';

const DEFAULT_TIMEOUT_MS = 1_000;
const LMS_PS_TIMEOUT_MS = 3_000;
const LMS_PS_MAX_BUFFER = 2 * 1024 * 1024;
const execFileAsync = promisify(execFile);

const own = (object, key) => Object.prototype.hasOwnProperty.call(object ?? {}, key);

function modelId(model) {
  return typeof model === 'string' ? model : model?.id;
}

function availabilityOf(model, resolved) {
  if (typeof resolved?.available === 'boolean') return resolved.available;
  if (typeof model?.available === 'boolean') return model.available;
  return null;
}

function abortAfter(timeoutMs) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  return { controller, timer };
}

async function bounded(operation, timeoutMs = DEFAULT_TIMEOUT_MS) {
  const { controller, timer } = abortAfter(timeoutMs);
  let timeoutTimer;
  try {
    return await Promise.race([
      Promise.resolve().then(() => operation(controller.signal)),
      new Promise((_, reject) => {
        timeoutTimer = setTimeout(() => reject(new Error('catalog-timeout')), timeoutMs);
      }),
    ]);
  } finally {
    clearTimeout(timer);
    clearTimeout(timeoutTimer);
  }
}

export function classifyProvider(provider) {
  // LM Studio's provider can dispatch through LM Link. Only a loaded instance
  // inventory proves this specific alias is physically local.
  if (provider === 'lmstudio') return { executionClass: 'lmstudio', locality: 'unknown', billing: 'free' };
  if (provider === 'claude-cli' || provider === 'codex-cli') return { executionClass: provider, locality: 'remote', billing: 'subscription' };
  return { executionClass: 'api', locality: 'unknown', billing: 'unknown' };
}

function catalogStateFor(providerId, model) {
  // This exact marker is generated by stack/provider-integration/catalog.mjs
  // for OmniRoute rows without a configured account. It is not a general
  // interpretation of model names or a network/authentication probe.
  if (providerId === 'omniroute' && typeof model?.name === 'string' && model.name.includes('; connect account;')) {
    return { catalogState: 'catalog-only', catalogStateSource: 'halo-catalog-label-not-live-entitlement-probe' };
  }
  return { catalogState: 'registered' };
}

function resolvedMetadata(model, resolved, state) {
  const modalities = Array.isArray(resolved?.inputModalities)
    ? [...resolved.inputModalities]
    : Array.isArray(model.inputModalities) ? [...model.inputModalities] : null;
  const reasoning = resolved?.reasoning
    ? {
        state: 'observed',
        efforts: Array.isArray(resolved.reasoning.efforts)
          ? resolved.reasoning.efforts.map((effort) => effort.id).filter((effort) => typeof effort === 'string')
          : [],
        defaultEffort: own(resolved.reasoning, 'defaultEffort') ? resolved.reasoning.defaultEffort : 'provider-default',
      }
    : { state: 'unknown' };
  return {
    metadataState: state,
    contextWindow: resolved?.context?.contextWindow,
    contextWindowState: typeof resolved?.context?.contextWindow === 'number' ? 'observed' : 'unknown',
    inputModalities: modalities,
    inputModalitiesState: modalities === null ? 'unknown' : 'observed',
    // Compatibility alias for the current policy surface; state above preserves unknown.
    capabilities: modalities ?? [],
    reasoning,
    // DSH 0.1.1-rc.2 LlmResolvedModelInfo exposes no tool-support metadata.
    toolSupport: { state: 'unknown' },
  };
}

async function nativeCatalog(subagents, timeoutMs) {
  const nativeProviders = [];
  const nativeCandidates = [];
  const nativeErrors = [];
  if (typeof subagents?.list !== 'function') {
    return { nativeCatalogState: 'unavailable', nativeProviders, nativeCandidates, nativeErrors };
  }

  let providers;
  try {
    providers = await bounded(() => subagents.list(), timeoutMs);
  } catch {
    nativeErrors.push({ reason: 'native-provider-catalog-unavailable' });
    return { nativeCatalogState: 'unavailable', nativeProviders, nativeCandidates, nativeErrors };
  }

  for (const id of providers ?? []) {
    if (typeof id !== 'string' || !id) {
      nativeErrors.push({ reason: 'native-provider-id-unavailable' });
      continue;
    }
    let provider;
    try {
      // Published runtimes expose getProvider(); get() is accepted for a compatible host API.
      provider = await bounded(() => {
        if (typeof subagents.getProvider === 'function') return subagents.getProvider(id);
        if (typeof subagents.get === 'function') return subagents.get(id);
        return undefined;
      }, timeoutMs);
    } catch {
      nativeErrors.push({ provider: id, reason: 'native-provider-lookup-unavailable' });
    }
    const capabilitySource = provider?.capabilities;
    const capabilities = capabilitySource && typeof capabilitySource === 'object'
      ? Object.fromEntries(['outputSchema', 'depthLimit', 'toolFilter', 'persona']
        .filter((key) => typeof capabilitySource[key] === 'boolean')
        .map((key) => [key, capabilitySource[key]]))
      : null;
    const row = {
      id,
      kind: 'native-subagent',
      catalogState: 'registered',
      providerState: provider ? 'observed' : 'unknown',
      modelCatalogState: 'unknown',
      capabilityState: capabilities ? 'observed' : 'unknown',
      capabilities,
      inheritsParentContext: typeof provider?.inheritsParentContext === 'boolean'
        ? provider.inheritsParentContext
        : null,
      continuable: provider ? typeof provider.prepareContinuable === 'function' : null,
    };
    nativeProviders.push(row);
  }
  return { nativeCatalogState: 'observed', nativeProviders, nativeCandidates, nativeErrors };
}

/** Catalog membership is advisory; this performs no inference, auth probe, or model-state operation. */
export async function census(llm, subagents, { timeoutMs = DEFAULT_TIMEOUT_MS } = {}) {
  const candidates = [];
  const providerErrors = [];
  const providers = [];
  let registered;
  try {
    registered = await bounded(() => llm?.listProviders?.() ?? [], timeoutMs);
  } catch {
    providerErrors.push({ reason: 'provider-catalog-unavailable' });
    registered = [];
  }

  for (const provider of registered ?? []) {
    const providerId = provider?.id;
    if (typeof providerId !== 'string' || !providerId) {
      providerErrors.push({ reason: 'provider-id-unavailable' });
      continue;
    }
    const providerRow = { id: providerId, name: provider.name ?? providerId, catalogState: 'registered' };
    providers.push(providerRow);
    let models;
    try {
      models = await bounded(() => llm.listModels(providerId), timeoutMs);
      providerRow.modelCatalogState = 'observed';
    } catch {
      providerRow.modelCatalogState = 'unavailable';
      providerErrors.push({ provider: providerId, reason: 'model-catalog-unavailable' });
      continue;
    }

    for (const model of models ?? []) {
      const id = modelId(model);
      if (typeof id !== 'string' || !id) {
        providerErrors.push({ provider: providerId, reason: 'model-id-unavailable' });
        continue;
      }
      let resolved;
      let metadataState = 'unavailable';
      if (typeof llm.resolveModelInfo === 'function') {
        try {
          resolved = await bounded((signal) => llm.resolveModelInfo(providerId, id, signal), timeoutMs);
          metadataState = resolved?.provider === providerId && resolved?.id === id ? 'resolved' : 'identity-mismatch';
          if (metadataState !== 'resolved') resolved = undefined;
        } catch {
          metadataState = 'unavailable';
        }
      }
      const metadata = resolvedMetadata(model, resolved, metadataState);
      const catalogState = catalogStateFor(providerId, model);
      candidates.push({
        candidateId: `${providerId}/${id}`,
        provider: providerId,
        model: id,
        ...classifyProvider(providerId),
        ...catalogState,
        // The registered provider route remains visible even when the model
        // row is catalog-only and is rejected by shadow policy.
        registeredRoute: true,
        // `available` is the policy contract. `availability` remains a
        // compatibility alias for consumers of earlier observation snapshots.
        available: availabilityOf(model, resolved),
        availability: availabilityOf(model, resolved),
        name: model.name ?? id,
        description: model.description,
        ...metadata,
        qualificationState: 'unknown',
      });
    }
  }

  return {
    capturedAt: new Date().toISOString(),
    providers,
    candidates,
    providerErrors,
    ...(await nativeCatalog(subagents, timeoutMs)),
  };
}

/** Read the local LM Studio catalog without issuing inference or model-state commands. */
export async function localRuntime(url = 'http://127.0.0.1:1234', { fetchImpl = globalThis.fetch, timeoutMs = 3_000 } = {}) {
  const endpoint = new URL('/api/v1/models', url).toString();
  const response = await fetchImpl(endpoint, { signal: AbortSignal.timeout(timeoutMs) });
  if (!response.ok) throw new Error('LM Studio catalog unavailable');
  const value = await response.json();
  return Array.isArray(value.models) ? value.models : Array.isArray(value.data) ? value.data : [];
}

/**
 * Observe loaded LM Studio execution origin only. `lms ps` is read-only: it
 * neither probes a remote endpoint nor changes model residency. A catalog row
 * absent from this Map remains transport-unknown; LM Studio alone is not proof
 * of a physically local runtime.
 */
export async function residentOrigins({ execFileImpl = execFileAsync } = {}) {
  const userProfile = process.env.USERPROFILE;
  if (typeof userProfile !== 'string' || !userProfile) throw new Error('USERPROFILE unavailable for lms ps');
  const executable = join(userProfile, '.lmstudio', 'bin', 'lms.exe');
  const result = await execFileImpl(executable, ['ps', '--json'], {
    timeout: LMS_PS_TIMEOUT_MS,
    maxBuffer: LMS_PS_MAX_BUFFER,
    windowsHide: true,
    encoding: 'utf8',
  });
  const stdout = typeof result === 'string' ? result : result?.stdout;
  const rows = JSON.parse(String(stdout));
  const models = Array.isArray(rows) ? rows : Array.isArray(rows?.models) ? rows.models : [];
  const observedAt = new Date().toISOString();
  const origins = new Map();
  for (const row of models) {
    if (typeof row?.modelKey !== 'string' || !row.modelKey) continue;
    origins.set(row.modelKey, {
      locality: row.deviceIdentifier == null ? 'local' : 'remote',
      source: 'lms ps --json/deviceIdentifier',
      observedAt,
    });
  }
  return origins;
}

function catalogRequested(row) {
  return {
    source: 'lmstudio/api/v1/models/catalog',
    quantization: row.quantization?.name ?? row.quantization,
    selectedVariant: row.selected_variant,
  };
}

function loadedProfile(row, instance) {
  const config = instance.config ?? {};
  return {
    source: 'lmstudio/api/v1/models/loaded-instance',
    locality: 'local',
    localitySource: 'lmstudio/api/v1/models/loaded-instance',
    localInstanceState: 'singleton-loaded',
    localAlias: row.key ?? row.id,
    localInstanceId: instance.id ?? null,
    quantization: row.quantization?.name ?? row.quantization,
    contextWindow: config.context_length,
    parallelSlots: config.parallel,
    loadConfig: config,
    requested: catalogRequested(row),
  };
}

/**
 * Return only unambiguous loaded-alias profiles in the Map. Cold and ambiguous
 * aliases are retained on attached Maps so callers cannot mistake catalog facts
 * or the first loaded instance for a route's active execution configuration.
 */
export function enrichLocal(data) {
  const rows = Array.isArray(data) ? data : data?.models ?? data?.data ?? [];
  const map = new Map();
  map.coldAliases = new Map();
  map.ambiguousAliases = new Map();
  map.instances = new Map();
  for (const row of rows) {
    const alias = row?.key ?? row?.id;
    if (typeof alias !== 'string' || !alias) continue;
    const instances = Array.isArray(row.loaded_instances) ? row.loaded_instances : [];
    if (instances.length === 0) {
      map.coldAliases.set(alias, { localInstanceState: 'cold', localAlias: alias, requested: catalogRequested(row) });
      continue;
    }
    if (instances.length !== 1) {
      const ambiguity = {
        localInstanceState: 'ambiguous',
        localAlias: alias,
        requested: catalogRequested(row),
        instances: instances.map((instance) => ({ id: instance.id ?? null, config: instance.config ?? {} })),
      };
      map.ambiguousAliases.set(alias, ambiguity);
      for (const instance of instances) if (instance.id) map.instances.set(instance.id, ambiguity);
      continue;
    }
    const profile = loadedProfile(row, instances[0]);
    map.set(alias, profile);
    if (instances[0].id && instances[0].id !== alias) map.instances.set(instances[0].id, profile);
  }
  return map;
}
